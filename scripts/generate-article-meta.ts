/**
 * generate-article-meta.ts — regenerate the blog article metadata index
 * and the lazy batch-loader map.
 *
 * Why this exists (Cloudflare Workers startup-CPU fix, 2026-11-24):
 * routes must never import the full ~10 MB article corpus eagerly.
 * This script derives two generated modules from the corpus:
 *
 *   src/lib/articles-meta.generated.ts
 *     ARTICLE_META — every article's metadata (no content/faqs/howTo),
 *     in corpus order, with SERP meta overrides applied.
 *     ARTICLE_BATCH_BY_SLUG — slug → batch number (0 = seed module),
 *     first occurrence wins, matching getArticleBySlug() semantics.
 *
 *   src/lib/pages/loaders.generated.ts
 *     BATCH_LOADERS — batch number → dynamic-import loader returning
 *     that batch's full articles. Each batch stays its own chunk and
 *     is loaded only when one of its articles is actually rendered.
 *
 * Run after adding/editing any src/lib/pages/Batch*.ts or seed article:
 *   npx tsx scripts/generate-article-meta.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { ARTICLES, applyMetaOverrides } from '../src/lib/articles-seed';
import type { Article, ArticleMeta } from '../src/lib/articles';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function batchOrder(): number[] {
  const indexSrc = readFileSync(join(ROOT, 'src/lib/pages/index.ts'), 'utf8');
  const order = [...indexSrc.matchAll(/import \{ batch(\d+) \} from '\.\/Batch\d+';/g)].map((m) =>
    Number(m[1])
  );
  if (order.length === 0) throw new Error('No batch imports found in src/lib/pages/index.ts');
  return order;
}

function toMeta(a: Article): ArticleMeta {
  const { content: _content, faqs: _faqs, howTo: _howTo, ...meta } = applyMetaOverrides(a);
  return meta;
}

async function main() {
  const order = batchOrder();
  const meta: ArticleMeta[] = [];
  const batchBySlug: Record<string, number> = {};

  for (const a of ARTICLES) {
    meta.push(toMeta(a));
    if (!(a.slug in batchBySlug)) batchBySlug[a.slug] = 0;
  }

  for (const n of order) {
    const mod = (await import(pathToFileURL(join(ROOT, `src/lib/pages/Batch${n}.ts`)).href)) as {
      [k: string]: Article[];
    };
    const batch = mod[`batch${n}`];
    if (!Array.isArray(batch)) throw new Error(`Batch${n}.ts does not export batch${n}`);
    for (const a of batch) {
      meta.push(toMeta(a));
      if (!(a.slug in batchBySlug)) batchBySlug[a.slug] = n;
    }
  }

  const header =
    '/**\n * GENERATED by scripts/generate-article-meta.ts — do not edit by hand.\n' +
    ' * Regenerate: npx tsx scripts/generate-article-meta.ts\n */\n';

  const metaFile =
    header +
    "import type { ArticleMeta } from './articles';\n\n" +
    `export const ARTICLE_META: ArticleMeta[] = ${JSON.stringify(meta, null, 1)};\n\n` +
    `export const ARTICLE_BATCH_BY_SLUG: Record<string, number> = ${JSON.stringify(batchBySlug, null, 1)};\n`;
  writeFileSync(join(ROOT, 'src/lib/articles-meta.generated.ts'), metaFile);

  const loadersFile =
    header +
    "import type { Article } from '../articles';\n\n" +
    'export const BATCH_LOADERS: Record<number, () => Promise<Article[]>> = {\n' +
    order.map((n) => `  ${n}: async () => (await import('./Batch${n}')).batch${n},`).join('\n') +
    '\n};\n';
  writeFileSync(join(ROOT, 'src/lib/pages/loaders.generated.ts'), loadersFile);

  console.log(
    `Wrote ${meta.length} article metadata entries across ${order.length} batches ` +
      `(${Object.keys(batchBySlug).length} unique slugs).`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
