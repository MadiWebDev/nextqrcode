export const ALL_CURRENCIES: Currency[] = [...POPULAR_CURRENCIES, ...OTHER_CURRENCIES];

const BY_CODE = new Map(ALL_CURRENCIES.map((cur) => [cur.code, cur]));

/** Minor-unit decimals for a currency (JPY=0, USD=2, KWD=3). Unknown codes default to 2. */
export const currencyDigits = (code: string): number => BY_CODE.get(code)?.digits ?? 2;

/** Label for selectors, e.g. "PKR — Pakistani Rupee". */
export const currencyLabel = (code: string): string => {
  const cur = BY_CODE.get(code);
  return cur ? `${cur.code} — ${cur.name}` : code;
};
