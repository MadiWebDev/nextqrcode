/**
 * ICO container writer. The .ico format is a simple documented container:
 * an ICONDIR header followed by one ICONDIRENTRY per image and the image
 * data itself (PNG-compressed entries are supported by all modern Windows
 * versions and browsers). We pack real PNG encodes at each requested size —
 * no fake or placeholder icon data.
 */

export interface IcoEntry {
  /** Square size in px (16..256). 256 is stored as byte 0 per the spec. */
  size: number;
  png: Uint8Array;
}

export function buildIco(entries: IcoEntry[]): Uint8Array {
  const sorted = [...entries].sort((a, b) => a.size - b.size);
  const headerSize = 6 + sorted.length * 16;
  let total = headerSize;
  for (const e of sorted) total += e.png.length;
  const out = new Uint8Array(total);
  const dv = new DataView(out.buffer);
  dv.setUint16(0, 0, true); // reserved
  dv.setUint16(2, 1, true); // type: icon
  dv.setUint16(4, sorted.length, true);
  let offset = headerSize;
  sorted.forEach((entry, i) => {
    const base = 6 + i * 16;
    out[base] = entry.size >= 256 ? 0 : entry.size; // width byte (0 = 256)
    out[base + 1] = entry.size >= 256 ? 0 : entry.size; // height byte
    out[base + 2] = 0; // palette count
    out[base + 3] = 0; // reserved
    dv.setUint16(base + 4, 1, true); // colour planes
    dv.setUint16(base + 6, 32, true); // bits per pixel
    dv.setUint32(base + 8, entry.png.length, true);
    dv.setUint32(base + 12, offset, true);
    out.set(entry.png, offset);
    offset += entry.png.length;
  });
  return out;
}

/** The standard favicon/app-icon size set generated by the tool. */
export const FAVICON_SIZES = [16, 32, 48, 180, 192, 512] as const;

/** Sample HTML snippet shipped with the icon ZIP. */
export function faviconHtmlSnippet(): string {
  return [
    '<link rel="icon" href="/favicon.ico" sizes="48x48">',
    '<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32x32.png">',
    '<link rel="icon" type="image/png" sizes="16x16" href="/favicon-16x16.png">',
    '<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png">',
    '<link rel="icon" type="image/png" sizes="192x192" href="/android-chrome-192x192.png">',
    '<link rel="icon" type="image/png" sizes="512x512" href="/android-chrome-512x512.png">',
    '',
  ].join('\n');
}
